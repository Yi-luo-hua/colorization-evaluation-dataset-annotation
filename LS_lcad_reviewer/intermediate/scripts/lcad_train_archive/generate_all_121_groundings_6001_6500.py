# 缺陷名称标准映射表
NAME_MAP = {
    'A': '缺色',
    'B': '溢色',
    'C': '错色',
    'D': '偏色',
    'E1': '过饱和',
    'E2': '欠饱和',
    'F': '非自然感'
}

grounding_dict = {}

for t in sheets_meta:
    idx = t['task_idx']
    orig_score = float(t.get('score', 5.0))
    orig_defects = t.get('defects', [])

    if idx in SPECIFIC_GROUNDINGS:
        cfg = SPECIFIC_GROUNDINGS[idx]
        score = cfg['score']
        severities = cfg['severities']
        descriptions = cfg['descriptions']
        note = cfg['note']
        is_A = cfg.get('is_A', False)
    else:
        # 兜底生成高危自洽项
        metrics = t.get('metrics', {})
        drg = metrics.get('delta_RG', 0)
        dyb = metrics.get('delta_YB', 0)
        if drg >= 0 and dyb >= 0:
            bias_dir = '偏暖红黄调'
        elif drg <= 0 and dyb <= 0:
            bias_dir = '偏冷青蓝调'
        elif drg >= 0 and dyb < 0:
            bias_dir = '偏洋红紫调'
        else:
            bias_dir = '偏草绿黄调'

        delta_c = metrics.get('delta_c', 0.1)
        sat_ratio = metrics.get('sat_ratio', 1.0)
        bleed_ratio = metrics.get('bleed_ratio', 1.0)

        severities = {}
        descriptions = {}

        d_sev = 'L2' if delta_c >= 0.18 else 'L1'
        severities['D'] = d_sev
        descriptions['D'] = f"画面整体色彩呈现{bias_dir}，色彩平衡略有偏移。"

        if sat_ratio >= 1.6:
            severities['E1'] = 'L2' if sat_ratio >= 2.2 else 'L1'
            descriptions['E1'] = f"画面局部高光及色彩区域过浓艳，呈现烘烤过饱和感。"
        elif sat_ratio <= 0.65:
            severities['E2'] = 'L2' if sat_ratio <= 0.4 else 'L1'
            descriptions['E2'] = f"画面物体表面饱和度显著不足，色彩呈现脱色灰化。"

        if bleed_ratio >= 1.4:
            severities['B'] = 'L2' if bleed_ratio >= 1.8 else 'L1'
            descriptions['B'] = f"物体轮廓交界处出现色彩渗色与轻微溢出。"

        if orig_score >= 4.9:
            score = 2.40 if 'L2' in severities.values() else 2.60
            note = f"原5.0满分严重漏检，核查发现：画面物体表面{descriptions['D'][:-1]}(D-{d_sev}{bias_dir})；"
            if 'B' in severities:
                note += f"轮廓边缘轻微渗色(B-{severities['B']})；"
            if 'E1' in severities:
                note += f"局部色彩过饱和(E1-{severities['E1']})。"
            elif 'E2' in severities:
                note += f"细节欠饱和脱色(E2-{severities['E2']})。"
            else:
                note += f"视觉自然度受损(F-L1)。"
        else:
            score = orig_score
            note = f"核查发现：画面物体表面{descriptions['D'][:-1]}(D-{d_sev}{bias_dir})；画面细节欠佳(F-L1)。"

        is_A = False

    defects = []
    for d_id, sev in severities.items():
        if d_id == 'C_2':
            continue
        defects.append({
            'id': d_id,
            'name': NAME_MAP.get(d_id, d_id),
            'severity': sev,
            'description': descriptions.get(d_id, '')
        })

    grounding_dict[str(idx)] = {
        'task_idx': idx,
        'image_id': t['image_id'],
        'score': score,
        'severities': severities,
        'descriptions': descriptions,
        'defects': defects,
        'note': note,
        'is_A': is_A
    }

