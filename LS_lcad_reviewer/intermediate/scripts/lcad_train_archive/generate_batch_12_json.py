results = {}
revised_count = 0
passed_count = 0

for it in batch_items:
    tid = it["task_id"]
    iid = it["image_id"]
    if tid not in decisions:
        raise ValueError(f"Task ID {tid} missing from decisions dictionary!")
    status, def_tuples, note = decisions[tid]

    defects = []
    for def_id, sev, desc in def_tuples:
        defects.append({
            "id": def_id,
            "name": DEFECT_NAMES[def_id],
            "severity": sev,
            "description": desc
        })

    if status == "改判":
        revised_count += 1
    else:
        passed_count += 1

    results[str(tid)] = {
        "task_id": tid,
        "image_id": iid,
        "status": status,
        "defects": defects,
        "note": note,
        "reviewed_score": None,
        "needs_rescoring": True
    }

output_data = {
    "batch_no": 12,
    "total_items": len(batch_items),
    "revised_count": revised_count,
    "passed_count": passed_count,
    "results": results
}

out_path = Path("LS_lcad_reviewer/intermediate/audits/grounding_zero_defects_batch_12.json")
with open(out_path, "w", encoding="utf-8") as f:
    json.dump(output_data, f, ensure_ascii=False, indent=2)

print(f"Successfully generated {out_path}!")
