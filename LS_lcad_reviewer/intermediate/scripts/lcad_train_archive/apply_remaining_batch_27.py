# --- 严禁出现的抽象占位违禁词清单 ---
FORBIDDEN_WORDS = [
    "关键区域", "某些区域", "局部区域", "特定区域", "部分区域",
    "画面区域", "关键主体", "某些物体", "某些部位", "局部某些",
    "关键部位", "主体部位", "某些细节", "某些地方", "局部地方"
]

def validate_reviews(reviews: dict):
    """严格校验审校字典的具象实体定物规范与逻辑自洽性"""
    errors = []
    for task_id, item in reviews.items():
        note = item.get("note", "")
        defects = item.get("defects", [])
        
        # 1. 违禁词检查
        for fw in FORBIDDEN_WORDS:
            if fw in note:
                errors.append(f"Task #{task_id} note 包含抽象占位违禁词: '{fw}'")
            for d in defects:
                desc = d.get("description", "")
                if fw in desc:
                    errors.append(f"Task #{task_id} defect [{d.get('id')}] description 包含违禁词: '{fw}'")

        # 2. 互斥校验 (E1 与 E2 严禁共存)
        d_ids = {d["id"] for d in defects}
        if "E1" in d_ids and "E2" in d_ids:
            errors.append(f"Task #{task_id} 同时包含互斥的 E1(过饱和) 与 E2(欠饱和)！")

        # 3. 熔断校验 (A 项不可有 severity)
        if "A" in d_ids:
            for d in defects:
                if d["id"] == "A" and d.get("severity", "") != "":
                    errors.append(f"Task #{task_id} 命中A项熔断，但 severity 不为空: '{d.get('severity')}'")

        # 4. 规范放行检查
        if note == "审查通过" and len(defects) > 0:
            errors.append(f"Task #{task_id} note 为 '审查通过'，但 defects 不为空！")
        if note != "审查通过" and len(defects) == 0:
            errors.append(f"Task #{task_id} defects 为空，但 note 不为 '审查通过'！")

    if errors:
        print(f"[ERROR] 发现 {len(errors)} 处规范冲突：")
        for e in errors:
            print(f"  - {e}")
        return False
    print("[PASS] 词法与逻辑规范 100% 通过！")
    return True

def apply_to_dataset(file_path: str, reviews: dict, is_clean: bool = False):
    """将审校结果双向同步写入交付数据集"""
    with open(file_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    updated_count = 0
    pass_count = 0
    revise_count = 0

    for ann in data.get("annotations", []):
        tid = ann.get("human_review", {}).get("task_id")
        if tid in reviews:
            rev = reviews[tid]
            ann["review_status"] = rev["status"]
            ann["defects"] = rev["defects"]
            
            # 双轨制 review_note 处理
            if is_clean:
                ann["review_note"] = ""
            else:
                ann["review_note"] = rev["note"]

            # 熔断 A 逻辑
            d_ids = {d["id"] for d in rev["defects"]}
            if "A" in d_ids:
                ann["reviewed_score"] = 1.0
                ann["needs_rescoring"] = False
            else:
                ann["reviewed_score"] = None
                ann["needs_rescoring"] = True

            updated_count += 1
            if rev["note"] == "审查通过":
                pass_count += 1
            else:
                revise_count += 1

    with open(file_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    version_str = "clean" if is_clean else "all"
    print(f"[OK] 已同步 {version_str} 版本: {file_path}")
    print(f"   - 成功覆盖: {updated_count} 组 (其中 PASS: {pass_count} 组, REVISE: {revise_count} 组)")

