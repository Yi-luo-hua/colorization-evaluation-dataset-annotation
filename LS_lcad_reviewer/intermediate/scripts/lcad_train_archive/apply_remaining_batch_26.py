def main():
    print(f"=== 开始应用 Batch 26 具象定物判决字典 (共 {len(BATCH_26_REVIEWS)} 组任务) ===")

    # 1. 严格防错红线与逻辑互斥校验
    forbidden_tokens = ["关键区域", "某些区域", "局部区域", "该区域", "主体区域"]
    errors = []

    for tid, rev in BATCH_26_REVIEWS.items():
        # 违禁词检查
        for token in forbidden_tokens:
            if token in rev["note"]:
                errors.append(f"Task #{tid} 评语命中违禁抽象词: '{token}'")
            for d in rev["defects"]:
                if token in d["description"]:
                    errors.append(f"Task #{tid} 缺陷描述命中违禁抽象词: '{token}'")

        # 逻辑互斥检验 (E1 与 E2 严禁共存)
        defect_ids = [d["id"] for d in rev["defects"]]
        if "E1" in defect_ids and "E2" in defect_ids:
            errors.append(f"Task #{tid} 同时存在矛盾的 E1(过饱和) 与 E2(欠饱和)！")

        # A 项熔断检验
        if "A" in defect_ids:
            if len(defect_ids) > 1:
                errors.append(f"Task #{tid} 命中A项熔断但包含其他缺陷: {defect_ids}")
            for d in rev["defects"]:
                if d["id"] == "A" and d["severity"] != "":
                    errors.append(f"Task #{tid} A项缺陷的severity必须为空字符串！")

    if errors:
        print("[FAIL] 校验发现以下致命逻辑/语言错误:")
        for err in errors:
            print(f"  - {err}")
        sys.exit(1)
    else:
        print("[PASS] 抽象代词过滤与逻辑互斥断言 100% 通过！")

    # 2. 导出纯净中间定物 JSON
    out_grounding_path = "LS_lcad_reviewer/intermediate/audits/grounding_remaining_batch_26.json"
    os.makedirs(os.path.dirname(out_grounding_path), exist_ok=True)
    with open(out_grounding_path, "w", encoding="utf-8") as f:
        json.dump(BATCH_26_REVIEWS, f, ensure_ascii=False, indent=2)
    print(f"[OK] 具象定物字典已保存: {out_grounding_path}")

    # 3. 双向同步应用到 reviewed_1_10000_all.json 与 reviewed_1_10000_clean.json
    all_path = "LS_lcad_reviewer/exports/reviewed_1_10000_all.json"
    clean_path = "LS_lcad_reviewer/exports/reviewed_1_10000_clean.json"

    for file_path, is_clean in [(all_path, False), (clean_path, True)]:
        if not os.path.exists(file_path):
            print(f"[WARN] 文件不存在，跳过: {file_path}")
            continue

        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        updated_count = 0
        pass_count = 0
        revise_count = 0

        for ann in data["annotations"]:
            tid = ann["human_review"]["task_id"]
            if tid in BATCH_26_REVIEWS:
                rev = BATCH_26_REVIEWS[tid]
                ann["review_status"] = rev["status"]
                ann["defects"] = rev["defects"]

                # 双轨制评语控制
                if is_clean:
                    ann["review_note"] = ""
                else:
                    ann["review_note"] = rev["note"]

                # 判定重算标记
                defect_ids = [d["id"] for d in rev["defects"]]
                if "A" in defect_ids:
                    ann["reviewed_score"] = 1.0
                    ann["needs_rescoring"] = False
                else:
                    ann["reviewed_score"] = None
                    ann["needs_rescoring"] = True

                if len(rev["defects"]) == 0:
                    pass_count += 1
                else:
                    revise_count += 1
                updated_count += 1

        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

        mode_name = "纯净交付版 (clean)" if is_clean else "完整过程版 (all)"
        print(f"[OK] 已同步更新 {mode_name}: {file_path}")
        print(f"   - 成功覆盖任务: {updated_count} 组 (放行 PASS: {pass_count} 组, 改判 REVISE: {revise_count} 组)")

    print("=== Batch 26 同步操作圆满完成 ===")


if __name__ == "__main__":
    main()
