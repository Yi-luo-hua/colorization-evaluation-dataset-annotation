# Construct results dictionary
results = {}
revised_count = 0
passed_count = 0
stats_defects = {}

for it in batch_items:
    tid = it["task_id"]
    iid = it["image_id"]
    status, def_tuples, note = decisions[tid]
    
    defects = []
    for def_id, sev, desc in def_tuples:
        defects.append({
            "id": def_id,
            "name": DEFECT_NAMES[def_id],
            "severity": sev,
            "description": desc
        })
        stats_defects[def_id] = stats_defects.get(def_id, 0) + 1
    
    if status == "改判":
        revised_count += 1
    else:
        passed_count += 1
        
    results[str(tid)] = {
        "task_id": tid,
        "image_id": iid,
        "status": status,
        "defects": defects,
        "note": note,
        "reviewed_score": None,
        "needs_rescoring": True
    }

