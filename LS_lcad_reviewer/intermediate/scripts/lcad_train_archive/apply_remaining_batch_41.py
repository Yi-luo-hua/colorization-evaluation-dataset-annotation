DEFECT_NAMES = {
    "A": "缺色",
    "B": "溢色",
    "C": "错色",
    "D": "偏色",
    "E1": "过饱和",
    "E2": "欠饱和",
    "F": "视觉自然度"
}

def run():
    print(f"Batch 41 defined reviews count: {len(batch_41_reviews)}")
    out_grounding_path = Path("LS_lcad_reviewer/intermediate/audits/grounding_remaining_batch_41.json")
    out_grounding_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_grounding_path, "w", encoding="utf-8") as f:
        json.dump(batch_41_reviews, f, ensure_ascii=False, indent=2)
    print(f"Exported grounding reviews to {out_grounding_path}")

    # Synchronize reviewed_1_10000_all.json and reviewed_1_10000_clean.json
    all_path = Path("LS_lcad_reviewer/exports/reviewed_1_10000_all.json")
    clean_path = Path("LS_lcad_reviewer/exports/reviewed_1_10000_clean.json")
    
    with open(all_path, "r", encoding="utf-8") as f:
        data_all = json.load(f)
    with open(clean_path, "r", encoding="utf-8") as f:
        data_clean = json.load(f)
        
    ann_all_map = {item["human_review"]["task_id"]: item for item in data_all["annotations"]}
    ann_clean_map = {item["human_review"]["task_id"]: item for item in data_clean["annotations"]}
    
    updated_count = 0
    passed_count = 0
    revised_count = 0
    
    for task_id, review in batch_41_reviews.items():
        if task_id not in ann_all_map:
            print(f"Warning: task_id {task_id} not found in annotations!")
            continue
            
        item_all = ann_all_map[task_id]
        item_clean = ann_clean_map[task_id]
        
        if review["pass"]:
            # Clean pass
            item_all["defects"] = []
            item_all["review_note"] = "审查通过"
            item_all["reviewed_score"] = None
            item_all["needs_rescoring"] = True
            
            item_clean["defects"] = []
            item_clean["review_note"] = ""
            item_clean["reviewed_score"] = None
            item_clean["needs_rescoring"] = True
            passed_count += 1
        else:
            # Revised defects
            defects_list = []
            for code, sev in review["severities"].items():
                defects_list.append({
                    "id": code,
                    "name": DEFECT_NAMES[code],
                    "severity": sev,
                    "description": review["descriptions"][code]
                })
            
            item_all["defects"] = defects_list
            item_all["review_note"] = review["note"]
            item_all["reviewed_score"] = None
            item_all["needs_rescoring"] = True
            
            item_clean["defects"] = defects_list
            item_clean["review_note"] = ""
            item_clean["reviewed_score"] = None
            item_clean["needs_rescoring"] = True
            revised_count += 1
            
        updated_count += 1

    with open(all_path, "w", encoding="utf-8") as f:
        json.dump(data_all, f, ensure_ascii=False, indent=2)
    with open(clean_path, "w", encoding="utf-8") as f:
        json.dump(data_clean, f, ensure_ascii=False, indent=2)
        
    print(f"Updated: {updated_count} (Passed: {passed_count}, Revised: {revised_count})")
    print(f"Synchronized {all_path}")
    print(f"Synchronized {clean_path}")

if __name__ == "__main__":
    run()
