def main():
    print("=== 开始执行 Batch 22 具象定物审查与同步 ===")

    # 1. 验证任务覆盖数量
    with open(AUDITS_DIR / "remaining_visual_audit_plan_50_batches.json", "r", encoding="utf-8") as f:
        plan = json.load(f)
    batches = {b["batch_no"]: b for b in plan["batches"]}
    b_items = batches[22]["items"]
    expected_ids = [t["task_id"] for t in b_items]

    print(f"Plan 规划任务数: {len(expected_ids)}")
    print(f"Reviews 评审记录数: {len(REVIEWS)}")

    missing = set(expected_ids) - set(REVIEWS.keys())
    if missing:
        print(f"错误: 存在未覆盖的任务: {missing}")
        return False
    extra = set(REVIEWS.keys()) - set(expected_ids)
    if extra:
        print(f"错误: 存在超出规划的任务: {extra}")
        return False

    # 2. 严格核验定物描述合规性
    pass_count = 0
    grounding_dict = {}
    for task_id, rev in REVIEWS.items():
        if rev == "PASS":
            pass_count += 1
            grounding_dict[str(task_id)] = {
                "status": "PASS",
                "defects": [],
                "note": "审查通过"
            }
            continue

        is_a = rev.get("is_A", False)
        defects_list = []
        d_ids = set()
        for d_id, sev, desc in rev["defects"]:
            d_ids.add(d_id)
            # 违禁词断言
            for fw in FORBIDDEN_WORDS:
                if fw in desc:
                    raise ValueError(f"Task #{task_id} 描述中包含抽象占位违禁词: {fw}")
            if is_a:
                if sev != "":
                    raise ValueError(f"Task #{task_id} 命中熔断项 A 时 severity 必须为空字符串！")
            else:
                if sev not in ["L1", "L2", "L3"]:
                    raise ValueError(f"Task #{task_id} 缺陷 {d_id} 的 severity 必须为 L1/L2/L3！")

            defects_list.append({
                "id": d_id,
                "name": DEFECT_NAMES[d_id],
                "severity": sev,
                "description": desc
            })

        # 互斥断言: E1 与 E2 严禁共存
        if "E1" in d_ids and "E2" in d_ids:
            raise ValueError(f"Task #{task_id} 错误同时包含互斥缺陷 E1 与 E2！")

        grounding_dict[str(task_id)] = {
            "status": "REVISED",
            "is_A": is_a,
            "defects": defects_list,
            "note": rev["note"]
        }

    print(f"审查校验完全通过！放行: {pass_count} 组, 改判: {len(REVIEWS) - pass_count} 组")

    # 3. 输出 grounding_remaining_batch_22.json
    with open(OUT_GROUNDING, "w", encoding="utf-8") as f:
        json.dump(grounding_dict, f, ensure_ascii=False, indent=2)
    print(f"成功导出定物字典: {OUT_GROUNDING.name}")

    # 4. 同步更新 reviewed_1_10000_all.json 与 reviewed_1_10000_clean.json
    print(f"正在加载全量数据集: {ALL_JSON.name} ...")
    with open(ALL_JSON, "r", encoding="utf-8") as f:
        all_data = json.load(f)

    with open(CLEAN_JSON, "r", encoding="utf-8") as f:
        clean_data = json.load(f)

    all_map = {item["human_review"]["task_id"]: item for item in all_data["annotations"]}
    clean_map = {item["human_review"]["task_id"]: item for item in clean_data["annotations"]}

    updated_count = 0
    for task_id, g_info in grounding_dict.items():
        tid = int(task_id)
        if tid not in all_map:
            raise KeyError(f"Task #{tid} 在全量数据集中未找到！")

        target_all = all_map[tid]
        target_clean = clean_map[tid]

        if g_info["status"] == "PASS":
            target_all["defects"] = []
            target_all["review_note"] = "审查通过"
            target_all["reviewed_score"] = None
            target_all["needs_rescoring"] = True
            target_all["review_status"] = "已核验"

            target_clean["defects"] = []
            target_clean["review_note"] = "审查通过"
            target_clean["reviewed_score"] = None
            target_clean["needs_rescoring"] = True
            target_clean["review_status"] = "已核验"
        else:
            is_a = g_info.get("is_A", False)
            target_all["defects"] = g_info["defects"]
            target_all["review_note"] = g_info["note"]
            target_all["reviewed_score"] = 1.0 if is_a else None
            target_all["needs_rescoring"] = False if is_a else True
            target_all["review_status"] = "已核验"

            target_clean["defects"] = g_info["defects"]
            target_clean["review_note"] = g_info["note"]
            target_clean["reviewed_score"] = 1.0 if is_a else None
            target_clean["needs_rescoring"] = False if is_a else True
            target_clean["review_status"] = "已核验"

        updated_count += 1

    print(f"同步更新条目数: {updated_count}")

    with open(ALL_JSON, "w", encoding="utf-8") as f:
        json.dump(all_data, f, ensure_ascii=False, indent=2)
    print(f"已回写更新: {ALL_JSON.name}")

    with open(CLEAN_JSON, "w", encoding="utf-8") as f:
        json.dump(clean_data, f, ensure_ascii=False, indent=2)
    print(f"已回写更新: {CLEAN_JSON.name}")

    print("=== Batch 22 同步处理圆满完成 ===")
    return True

if __name__ == "__main__":
    main()
